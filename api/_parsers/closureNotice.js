// Детектор объявления «объект закрыт / не работает / ремонт».
// Возвращает null или { notice, range? } для дальнейшего использования.

const { normalizeText, parseDateRange } = require('../_lib/timeParse');

// «закрыт» одно по себе ловило ложные срабатывания на «закрыта запись»,
// «закрытие сезона», «группа закрыта» — теперь требуется контекстный
// предлог (на ремонт / в связи / с DD.MM / по DD.MM / временно).
//
// «плановое отключени» расширено до «планов\w+ отключени», чтобы матчить
// инструментальный падеж («плановым отключением»), который встречается
// на странице большого бассейна.
//
// «отключени[еия]» расширено до «отключени\w*» по той же причине + теперь
// допускает «тепл» и «электр» помимо горячей/холодной воды.
const TRIGGER_RE = /(закрыт\w*\s+(?:на|в\s+связи|до|с|по|временно)|не\s+работает|приостанов|ремонтн|техническ|отключени\w*\s+(?:горяч|холодн|вод|тепл|электр)|планов\w+\s+отключени)/iu;

// Третий аргумент `plainText` — заранее очищенный текст root'а (с пробелами
// между блочными элементами). Если не передан — читаем напрямую через
// $root.text(), как раньше. Это нужно, потому что cheerio склеивает соседние
// <p>/<span> без пробелов: «года» + «плавательный» → «годаплавательный».
// Четвёртый аргумент `todayIso` — базовый год для дат без года («с 28.12 по 05.01»).
function detect($, $root, plainText, todayIso) {
  const text = plainText != null ? plainText : normalizeText($root.text());
  const tm = text.match(TRIGGER_RE);
  if (!tm) return null;

  // Берём предложение/абзац с триггером, чтобы не тащить весь HTML в notice.
  const sentences = text.split(/(?<=[\.\!?])\s+/);
  const matched = sentences.filter(s => TRIGGER_RE.test(s));
  const notice = (matched.join(' ') || text).slice(0, 280);

  // Диапазон дат ищем сначала в самом notice, затем — в окне вокруг триггера.
  // По всему тексту нельзя: подцепится чужой диапазон в духе «срок действия
  // абонементов с 01.09 по 31.05» из футера страницы.
  const windowText = text.slice(Math.max(0, tm.index - 120), tm.index + 360);
  const range = parseDateRange(notice, todayIso) || parseDateRange(windowText, todayIso);
  return { notice, range };
}

module.exports = { detect, TRIGGER_RE };
